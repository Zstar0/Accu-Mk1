"""AI chat tables (spec 2026-11-02 section 5): ACP providers, chats and their messages.

App tables like `flags`, so no `lims_` prefix. `create_all` makes them; nothing is migrated.
Portable column types only (JSON, never JSONB), so the SQLite test fixtures work.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Optional

from sqlalchemy import (
    JSON, Boolean, DateTime, ForeignKey, Index, Integer, String, Text, UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column

from database import Base


def _utcnow() -> datetime:
    """Naive UTC, matching the rest of the schema (`datetime.utcnow` is deprecated on 3.12+)."""
    return datetime.now(timezone.utc).replace(tzinfo=None)


class AcpProvider(Base):
    __tablename__ = "acp_providers"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    slug: Mapped[str] = mapped_column(String(32), unique=True, nullable=False)
    display_name: Mapped[str] = mapped_column(String(100), nullable=False)
    enabled: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)

    ssh_host: Mapped[str] = mapped_column(String(255), nullable=False)
    ssh_port: Mapped[int] = mapped_column(Integer, nullable=False, default=22)
    ssh_user: Mapped[str] = mapped_column(String(32), nullable=False)
    # The host's public key as "<keytype> <base64>".
    host_key: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Display only: renders the authorized_keys line the admin installs on the bot host.
    launcher_path: Mapped[str] = mapped_column(String(500), nullable=False)
    # The `from=` pin in that line (Mk1's egress IP; prod is the droplet's tailnet address).
    authorized_from: Mapped[str] = mapped_column(String(255), nullable=False)
    # Absolute POSIX path sent as `cwd` in session/new, session/load and session/resume.
    session_cwd: Mapped[str] = mapped_column(String(500), nullable=False)

    # Ed25519 generated by Mk1. The private half is Fernet-encrypted and never leaves the API.
    private_key_ciphertext: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    public_key: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    key_created_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)

    allowed_roles: Mapped[list[str]] = mapped_column(JSON, nullable=False, default=lambda: ["admin"])
    inject_mk1_tools: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    max_sessions: Mapped[int] = mapped_column(Integer, nullable=False, default=4)
    idle_minutes: Mapped[int] = mapped_column(Integer, nullable=False, default=15)
    permission_timeout_s: Mapped[int] = mapped_column(Integer, nullable=False, default=240)
    agent_approval_timeout_s: Mapped[int] = mapped_column(Integer, nullable=False, default=300)

    # Written by Test connection and by every real connect.
    last_test_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    last_test_ok: Mapped[Optional[bool]] = mapped_column(Boolean, nullable=True)
    last_test_error: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    last_agent_info: Mapped[Optional[dict[str, Any]]] = mapped_column(JSON, nullable=True)
    last_capabilities: Mapped[Optional[dict[str, Any]]] = mapped_column(JSON, nullable=True)

    created_by_user_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, nullable=False, default=_utcnow)
    updated_by_user_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, nullable=False, default=_utcnow, onupdate=_utcnow)


class AiChat(Base):
    """Chats are archived, never deleted, so approval decisions stay on record."""
    __tablename__ = "ai_chats"
    __table_args__ = (Index("ix_ai_chats_user_updated", "user_id", "updated_at"),)

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id"), nullable=False)
    provider_id: Mapped[int] = mapped_column(ForeignKey("acp_providers.id"), nullable=False)
    # First 60 characters of the first prompt.
    title: Mapped[str] = mapped_column(String(60), nullable=False, default="")
    # Null until the first prompt creates the agent session.
    acp_session_id: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    archived: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    created_at: Mapped[datetime] = mapped_column(DateTime, nullable=False, default=_utcnow)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, nullable=False, default=_utcnow, onupdate=_utcnow)


class AiChatMessage(Base):
    __tablename__ = "ai_chat_messages"
    # The unique constraint's index also serves the (chat_id, seq) lookups.
    __table_args__ = (UniqueConstraint("chat_id", "seq", name="uq_ai_chat_messages_chat_seq"),)

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    chat_id: Mapped[int] = mapped_column(ForeignKey("ai_chats.id"), nullable=False)
    seq: Mapped[int] = mapped_column(Integer, nullable=False)
    # user / assistant / permission / system
    role: Mapped[str] = mapped_column(String(20), nullable=False)
    text: Mapped[str] = mapped_column(Text, nullable=False, default="")
    # Page context, tool calls, stop reason, or for a permission row the decision record.
    meta: Mapped[Optional[dict[str, Any]]] = mapped_column(JSON, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, nullable=False, default=_utcnow)
