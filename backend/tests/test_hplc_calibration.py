CASES = FIXTURE["cases"]
BY_NAME = {c["name"]: c for c in CASES}
WARNING_KEYS = {"code", "level", "text"}


def _same(got, want, where):
    """Exact for everything but numbers, which compare by approx; bool is never a number."""
    if isinstance(want, dict):
        assert isinstance(got, dict) and set(got) == set(want), f"{where}: keys {got!r}"
        for key in want:
            _same(got[key], want[key], f"{where}.{key}")
    elif isinstance(want, list):
        assert isinstance(got, list) and len(got) == len(want), f"{where}: {got!r}"
        for i, (g, w) in enumerate(zip(got, want)):
            _same(g, w, f"{where}[{i}]")
    elif isinstance(want, (int, float)) and not isinstance(want, bool):
        assert isinstance(got, (int, float)) and not isinstance(got, bool), f"{where}: {got!r}"
        assert got == pytest.approx(want, rel=1e-9, abs=1e-9), f"{where}: {got!r} != {want!r}"
    else:
        assert got == want and type(got) is type(want), f"{where}: {got!r} != {want!r}"


def _work_out(case):
    if "replicate_of" in case:
        return work_out_sheet(replicate_prep(case["replicate_of"], case["inputs"]))
    return work_out_sheet(case["inputs"])


@pytest.mark.parametrize("case", CASES, ids=lambda c: c["name"])
def test_work_out_sheet_gives_the_lab_tool_answer(case):
    worked = _work_out(case)
    want = dict(case["expect"])
    want_warnings = want.pop("warnings")
    warnings = worked.pop("warnings")
    _same(worked, want, "sheet")
    assert [(w["code"], w["level"]) for w in warnings] == \
        [(w["code"], w["level"]) for w in want_warnings]


@pytest.mark.parametrize("case", CASES, ids=lambda c: c["name"])
def test_every_warning_has_text(case):
    for w in _work_out(case)["warnings"]:
        assert set(w) == WARNING_KEYS and isinstance(w["text"], str) and w["text"].strip()
        assert chr(0x2014) not in w["text"]  # no em dash


