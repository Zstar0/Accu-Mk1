"""work_out_sheet (plan 4 HPLC calibration curve worksheet, Task 2), held to the lab tool's own answers.

tests/fixtures/hplc_calibration_cases.json is generated by make_hplc_calibration_cases.cjs from the
tool's calc.js; every case goes through work_out_sheet (a replicate case through replicate_prep
first) and must give its `expect` (numbers to 1e-9, everything else exactly; a warning's text only
has to be there). Pure: no database."""
import ast
import copy
import json
from pathlib import Path

import pytest

import hplc_calibration
from hplc_calibration import (
    CAL_LEVEL_TARGETS,
    CAL_MIN_STOCK_MG,
    CAL_STOCK_AS_TOP_PCT,
    CAL_STOCK_DILUENT_UL,
    CAL_TOP_ALIQUOT_UL,
    COUNTERIONS,
    MS_IONS,
    PROTON_DA,
    blank_inputs,
    blank_replicate_inputs,
    default_curve_name,
    linear_fit,
    replicate_prep,
    standard_data_for,
    work_out_sheet,
)

FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "hplc_calibration_cases.json")
                     .read_text(encoding="utf-8"))
CASES = FIXTURE["cases"]
BY_NAME = {c["name"]: c for c in CASES}
WARNING_KEYS = {"code", "level", "text"}


def _same(got, want, where):
    """Exact for everything but numbers, which compare by approx; bool is never a number."""
    if isinstance(want, dict):
        assert isinstance(got, dict) and set(got) == set(want), f"{where}: keys {got!r}"
        for key in want:
            _same(got[key], want[key], f"{where}.{key}")
    elif isinstance(want, list):
        assert isinstance(got, list) and len(got) == len(want), f"{where}: {got!r}"
        for i, (g, w) in enumerate(zip(got, want)):
            _same(g, w, f"{where}[{i}]")
    elif isinstance(want, (int, float)) and not isinstance(want, bool):
        assert isinstance(got, (int, float)) and not isinstance(got, bool), f"{where}: {got!r}"
        assert got == pytest.approx(want, rel=1e-9, abs=1e-9), f"{where}: {got!r} != {want!r}"
    else:
        assert got == want and type(got) is type(want), f"{where}: {got!r} != {want!r}"


def _work_out(case):
    if "replicate_of" in case:
        return work_out_sheet(replicate_prep(case["replicate_of"], case["inputs"]))
    return work_out_sheet(case["inputs"])


@pytest.mark.parametrize("case", CASES, ids=lambda c: c["name"])
def test_work_out_sheet_gives_the_lab_tool_answer(case):
    worked = _work_out(case)
    want = dict(case["expect"])
    want_warnings = want.pop("warnings")
    warnings = worked.pop("warnings")
    _same(worked, want, "sheet")
    assert [(w["code"], w["level"]) for w in warnings] == \
        [(w["code"], w["level"]) for w in want_warnings]


@pytest.mark.parametrize("case", CASES, ids=lambda c: c["name"])
def test_every_warning_has_text(case):
    for w in _work_out(case)["warnings"]:
        assert set(w) == WARNING_KEYS and isinstance(w["text"], str) and w["text"].strip()
        assert chr(0x2014) not in w["text"]  # no em dash


def test_work_out_sheet_leaves_its_inputs_alone():
    case = BY_NAME["manual override"]
    before = copy.deepcopy(case["inputs"])
    work_out_sheet(case["inputs"])
    assert case["inputs"] == before


def test_counterions_and_ions_are_the_sources():
    assert COUNTERIONS == FIXTURE["counterions"]
    assert list(MS_IONS) == FIXTURE["ms_ions"]


def test_constants_are_the_sources():
    from catalog.method_run_params import HPLC_RUN_PARAM_DEFAULTS
    k = FIXTURE["constants"]
    assert PROTON_DA == k["proton_da"]
    assert list(CAL_LEVEL_TARGETS) == k["cal_level_targets"]
    assert (CAL_STOCK_DILUENT_UL, CAL_MIN_STOCK_MG, CAL_TOP_ALIQUOT_UL, CAL_STOCK_AS_TOP_PCT) == \
        (k["cal_stock_diluent_ul"], k["cal_min_stock_mg"], k["cal_top_aliquot_ul"], k["cal_stock_as_top_pct"])
    for key in ("diluent_density_mg_ml", "target_volume_ul", "volume_tolerance_pct"):
        assert HPLC_RUN_PARAM_DEFAULTS[key] == k[key]


def test_blank_inputs_are_the_blank_case():
    assert blank_inputs() == BY_NAME["blank sheet"]["inputs"]
    assert blank_inputs() is not blank_inputs()


def test_blank_replicate_inputs():
    assert blank_replicate_inputs(2) == {"notes": None, "levels": [
        {"peak_area": None, "purity": None, "rt": None}, {"peak_area": None, "purity": None, "rt": None}]}


def test_replicate_prep_takes_only_the_run_results():
    original = BY_NAME["no correction"]["inputs"]
    rep = replicate_prep(original, {"notes": "Inj2", "levels": [{"peak_area": 1.0}]})
    assert rep["notes"] == "Inj2" and rep["stock"] == original["stock"] and rep["net"] == original["net"]
    assert rep["levels"][0] == {**original["levels"][0], "peak_area": 1.0, "purity": None, "rt": None}
    assert all(L["peak_area"] is None for L in rep["levels"][1:])
    assert original["levels"][0]["peak_area"] == 8588.495


def test_linear_fit_ignores_a_pair_with_a_blank():
    fit = linear_fit([(1, 2), (None, 5), (2, 4)])
    assert fit["n"] == 2 and fit["slope"] == 2 and fit["intercept"] == 0 and fit["r2"] == 1


def test_linear_fit_all_areas_equal_has_no_r2():
    fit = linear_fit([(1, 5), (2, 5), (3, 5)])
    assert fit["slope"] == 0 and fit["r2"] is None


def test_linear_fit_one_point_has_no_line():
    assert linear_fit([(1, 2)]) == {"slope": None, "intercept": None, "r2": None, "n": 1}


def test_standard_data_for_keeps_only_fitted_points():
    worked = work_out_sheet(BY_NAME["four points, two blank areas"]["inputs"])
    data = standard_data_for(worked)
    assert data["concentrations"] == [L["actual_conc_ug_ml"] for L in worked["levels"][:4]]
    assert data["areas"] == [8400.629, 4240.415, 2167.877, 865.139]
    assert data["rts"] == [6.349, 6.387, 6.398, 6.403]


def test_standard_data_for_drops_rts_when_one_is_blank():
    inputs = copy.deepcopy(BY_NAME["no correction"]["inputs"])
    inputs["levels"][2]["rt"] = None
    data = standard_data_for(work_out_sheet(inputs))
    assert len(data["concentrations"]) == 6 and len(data["areas"]) == 6 and "rts" not in data


def test_stock_near_top_when_the_stock_lands_on_the_top_target():
    inputs = copy.deepcopy(BY_NAME["stock is the top level"]["inputs"])
    inputs["stock_as_top"] = False
    assert work_out_sheet(inputs)["stock_near_top"] is True  # 995 against 1000: 0.5 %, inside 5 %


def test_default_curve_name_matches_the_source():
    assert default_curve_name("Retatrutide", "1290A", "2026-02-05") == "1290A-2026-02-05-Retatrutide"
    assert default_curve_name("NAD+", "HPLC 1290b", None) == "HPLC1290b-undated-NAD"
    assert default_curve_name("", "", "") == "1290-undated-std"


def test_no_sum_builtin_in_the_port():
    tree = ast.parse(Path(hplc_calibration.__file__).read_text(encoding="utf-8"))
    banned = {"sum", "fsum", "mean", "fmean"}
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            name = getattr(node.func, "id", None) or getattr(node.func, "attr", None)
            assert name not in banned, f"line {node.lineno}: {name}()"
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            mods = [a.name for a in node.names] + [getattr(node, "module", None) or ""]
            assert not any(m.startswith(("statistics", "calculations")) for m in mods), mods
