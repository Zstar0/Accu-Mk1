"""compute_row (plan 3 HPLC prep worksheet, Task 3), held to the lab tool's own answers.

tests/fixtures/hplc_prep_cases.json is generated by make_hplc_prep_cases.cjs from the tool's
calc.js; every case goes through compute_row and must give its `expect` (numbers to 1e-9,
everything else exactly; a warning's text only has to be there). A second test holds every
fully weighed vial to plan 1's engine, the arithmetic Process HPLC will run on the promoted
prep. Pure: no database."""
import json
from pathlib import Path

import pytest

from hplc_prep import compute_row

FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "hplc_prep_cases.json")
                     .read_text(encoding="utf-8"))
RULES, PARAMS, CASES = FIXTURE["rules"], FIXTURE["params"], FIXTURE["cases"]
IDS = [c["name"] for c in CASES]
WARNING_KEYS = {"code", "vial", "peptide_id", "text"}


def _same(got, want, where):
    """Exact for everything but numbers, which compare by approx; bool is never a number."""
    if isinstance(want, dict):
        assert isinstance(got, dict) and set(got) == set(want), f"{where}: keys {got!r}"
        for key in want:
            _same(got[key], want[key], f"{where}.{key}")
    elif isinstance(want, list):
        assert isinstance(got, list) and len(got) == len(want), f"{where}: {got!r}"
        for i, (g, w) in enumerate(zip(got, want)):
            _same(g, w, f"{where}[{i}]")
    elif isinstance(want, (int, float)) and not isinstance(want, bool):
        assert isinstance(got, (int, float)) and not isinstance(got, bool), f"{where}: {got!r}"
        assert got == pytest.approx(want, rel=1e-9, abs=1e-9), f"{where}: {got!r} != {want!r}"
    else:
        assert got == want and type(got) is type(want), f"{where}: {got!r} != {want!r}"


def test_the_fixture_params_are_the_method_defaults():
    from catalog.method_run_params import HPLC_RUN_PARAM_DEFAULTS
    assert PARAMS == HPLC_RUN_PARAM_DEFAULTS


@pytest.mark.parametrize("case", CASES, ids=IDS)
def test_compute_row_gives_the_lab_tool_answer(case):
    row = compute_row(case["facts"], case["inputs"], RULES, PARAMS)
    want = dict(case["expect"])
    want_warnings = want.pop("warnings")
    warnings = row.pop("warnings")
    _same(row, want, "row")
    assert [(w["code"], w["vial"], w["peptide_id"]) for w in warnings] == \
        [(w["code"], w["vial"], w["peptide_id"]) for w in want_warnings]
    for w in warnings:
        assert set(w) == WARNING_KEYS and isinstance(w["text"], str) and w["text"].strip()


def test_a_row_with_no_prep_form_has_nothing_to_work_out():
    row = compute_row({"declared_mg": 10.0, "form": None, "peptide_id": 10,
                       "components": [{"peptide_id": 10, "declared_mg": 10.0, "vial": 1}]},
                      None, RULES, PARAMS)
    assert row["form"] is None and row["vials"] == [] and row["components"] == []
    assert row["warnings"] == [] and row["stock"] == {"total_diluent_ml": None, "problem": None}


def _vial_inputs(case, vial):
    return (case["inputs"].get("vials") or {}).get(str(vial["vial"])) or {}


def _weights(case, vial):
    """The engine's five weighings, as promote will build them. A neat (capsule) vial with a
    blank "+ diluent" weighing takes its empty weighing there. A bac row's full vial is its
    stock_vial_diluent_mg and the emptied vial its stock_vial_mg, which is how the engine's
    stock_volume_ml reads with_diluent and empty."""
    from calculations.hplc_processor import WeightInputs
    inputs, v = case["inputs"], _vial_inputs(case, vial)
    diluent = v.get("vial_diluent_mg")
    if vial["neat"] and diluent is None:
        diluent = v.get("vial_mg")
    return WeightInputs(stock_vial_empty=inputs.get("stock_vial_mg"),
                        stock_vial_with_diluent=inputs.get("stock_vial_diluent_mg"),
                        dil_vial_empty=v.get("vial_mg"), dil_vial_with_diluent=diluent,
                        dil_vial_with_diluent_and_sample=v.get("vial_all_mg"))


def _intermediate(case, vial):
    from calculations.hplc_processor import IntermediateWeights
    if not vial["two_step"]:
        return None
    v = _vial_inputs(case, vial)
    return IntermediateWeights(int_vial_empty=v.get("int_vial_mg"),
                               int_vial_with_diluent=v.get("int_vial_diluent_mg"),
                               int_vial_with_diluent_and_sample=v.get("int_vial_all_mg"))


@pytest.mark.parametrize("case", CASES, ids=IDS)
def test_the_engine_agrees_with_the_port_on_every_weighed_case(case):
    """The engine rounds each step's factor to 6 places before multiplying them, so a two-step
    total is held to a relative 1e-6 and each step's own factor to 1e-6."""
    from calculations.hplc_processor import calculate_dilution_factor
    row = compute_row(case["facts"], case["inputs"], RULES, PARAMS)
    for vial in row["vials"]:
        if vial["dilution_factor_total"] is None:
            continue
        d = calculate_dilution_factor(_weights(case, vial), PARAMS["diluent_density_mg_ml"],
                                      _intermediate(case, vial), form=row["form"],
                                      declared_volume_ml=case["inputs"].get("declared_volume_ml"))
        assert d["problem"] is None
        assert d["dilution_factor"] == pytest.approx(vial["actual"]["dilution_factor"], abs=1e-6)
        if vial["two_step"]:
            assert d["intermediate"]["dilution_factor"] == pytest.approx(
                vial["intermediate"]["actual"]["dilution_factor"], abs=1e-6)
        assert d["dilution_factor_total"] == pytest.approx(vial["dilution_factor_total"],
                                                           rel=1e-6, abs=1e-6)
        assert d["stock_volume_ml"] == pytest.approx(row["stock"]["total_diluent_ml"], abs=1e-6)
